// Tunebox service worker: makes the app open and run with no internet.
//  - Navigations: network first, fall back to the cached app shell.
//  - Everything else (hashed JS/CSS, icons): cache first, filled on demand.

// The build replaces both placeholders below: the version (a hash of the built
// file names, so every deploy gets a fresh cache) and the list of built files.
const VERSION = "__VERSION__";
const PRECACHE = /*PRECACHE*/ [];
const CACHE = `tunebox-${VERSION}`;
const SHELL = ["/", "/manifest.webmanifest", "/icon-192.png", "/icon-512.png"];

self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE);
      // Every built file, including lazy chunks (e.g. the tag parser), so the
      // first visit is already fully usable offline.
      await cache.addAll([...SHELL, ...PRECACHE]);
      await self.skipWaiting();
    })(),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)));
      await self.clients.claim();
    })(),
  );
});

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === "navigate") {
    event.respondWith(
      (async () => {
        try {
          const fresh = await fetch(request);
          const cache = await caches.open(CACHE);
          cache.put("/", fresh.clone());
          return fresh;
        } catch {
          return (await caches.match("/")) ?? Response.error();
        }
      })(),
    );
    return;
  }

  event.respondWith(
    (async () => {
      const cached = await caches.match(request);
      if (cached) return cached;
      const response = await fetch(request);
      if (response.ok) {
        const cache = await caches.open(CACHE);
        cache.put(request, response.clone());
      }
      return response;
    })(),
  );
});
